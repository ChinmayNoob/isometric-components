import { Plate } from "@/components/iso/react/draw";
import { GasTurbineLive } from "./live";
import scene from "./scene.json";
import "@/components/iso/iso.css";
import "@/components/iso/skin.css";
import "./gas-turbine.css";

export type GasTurbineProps = {
  fig?: string;
  title?: string;
  caption?: string;
};

const LABEL =
  "A single-shaft heavy-duty gas turbine generator set on its foundation: generator with air cooler and bus ducts, coupling, compressor and turbine in a split casing, a silo combustor standing on the casing, an inlet duct from a filter house on legs, and an exhaust diffuser into a stack, with lube oil and fuel gas skids alongside.";

/**
 * Epic figure: a gas turbine generator set that comes apart into its assemblies on hover and runs through a start
 * to full load. The scene (geometry, painter's order, explode moves) is generated by build.mjs; this server component
 * renders it, and the live component moves it.
 */
export function GasTurbine({ fig = "Fig 3", title = "Gas turbine generator set", caption }: GasTurbineProps) {
  const { W, H, back, front, data } = scene;
  return (
    <div className="iso iso-skin">
      <Plate
        fig={fig}
        title={title}
        readout="cold · assembled"
        hint={
          <>
            <span className="gt-hint-fine">Hover to take apart · S to start</span>
            <span className="gt-hint-touch">Tap a part · Start below</span>
          </>
        }
        caption={
          caption ??
          `A single-shaft gas turbine generator set of the kind at NTPC Anta, which has three units of ${data.unitMw} MW (ABB 13D2, 1989) and one ${153.2} MW steam turbine, ${data.stationMw} MW in all. Air drawn through the filter house is compressed, burned with fuel gas in the silo combustor, and expanded through the turbine, which drives the compressor and the generator on one shaft at ${data.rpm} rpm for a 50 Hz grid. The drawing is a general arrangement, not the unit's own drawings, and the start is shown time-compressed.`
        }
      >
        <GasTurbineLive data={data}>
          <svg className="iso-svg gt-back" viewBox={`0 0 ${W} ${H}`} role="img" aria-label={LABEL} dangerouslySetInnerHTML={{ __html: back }} />
          <svg className="iso-svg gt-front" viewBox={`0 0 ${W} ${H}`} aria-hidden="true" focusable="false">
            <g className="gt-machine" dangerouslySetInnerHTML={{ __html: front }} />
          </svg>
          {/* The flame layer sits over the machine: nothing stands in front of the silo window while the unit runs. */}
          <canvas className="gt-gl" aria-hidden="true" />
        </GasTurbineLive>
      </Plate>
    </div>
  );
}
